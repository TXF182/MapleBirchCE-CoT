# ============================================================================
# tools/pack.ps1 — MapleBirchCE-CoT 打包 + verifier 4/4
# 用法：& tools\pack.ps1              # 合并产物 + 校验 + SHA256（默认）
#       & tools\pack.ps1 -BuildZip    # 额外生成 MapleBirchCE-CoT-<v>.mod.zip（本地安装包，默认不产）
# 产出：javascript\maplebirchce-cot.js（生成物，绝不手改）
# ============================================================================
param([switch]$BuildZip)
$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot   # tools\.. -> 仓库根
$src = Join-Path $repo "javascript\src"
$out = Join-Path $repo "javascript\maplebirchce-cot.js"
$order = @("01-core.js", "02-shell.js", "03-cot-adapter.js")

$bootRaw = Get-Content -Raw -LiteralPath (Join-Path $repo "boot.json")
$boot = $bootRaw | ConvertFrom-Json

$parts = @()
foreach ($f in $order) {
    $p = Join-Path $src $f
    if (-not (Test-Path -LiteralPath $p)) { throw "缺失源文件: $f" }
    $parts += "/* ===== $f ===== */"
    $parts += (Get-Content -Raw -LiteralPath $p)
}
$banner = "/* MapleBirchCE-CoT built bundle (generated by tools\pack.ps1 - do not edit) */`r`n"
[IO.File]::WriteAllText($out, $banner + ($parts -join "`r`n"), (New-Object Text.UTF8Encoding $false))

# ---- verifier 4/4 ----
$results = @()
$results += [pscustomobject]@{ No = 1; Name = "boot.json 有效 JSON + 必备字段"; Ok = ($boot.name -eq "MapleBirchCE-CoT" -and $boot.version -and $boot.scriptFileList_inject_early -and $boot.dependenceInfo) }

$coreRaw = Get-Content -Raw -LiteralPath (Join-Path $src "01-core.js")
$coreVer = ([regex]::Match($coreRaw, 'MCE_VERSION = "([^"]+)"')).Groups[1].Value
$results += [pscustomobject]@{ No = 2; Name = "版本双源一致 boot=$($boot.version) src=$coreVer"; Ok = ($boot.version -eq $coreVer) }

$prodRaw = Get-Content -Raw -LiteralPath $out
$results += [pscustomobject]@{ No = 3; Name = "产物含标记 (window.mbCE_cot / mbStageCE / fab / panel)"; Ok = ($prodRaw.Contains("window.mbCE_cot") -and $prodRaw.Contains("mbStageCE") -and $prodRaw.Contains("_fab") -and $prodRaw.Contains("_panel")) }

$refs = @($boot.scriptFileList_inject_early) + @($boot.tweeFileList) + @($boot.additionFile)
$allRefs = $true
foreach ($r in $refs) {
    if (-not (Test-Path -LiteralPath (Join-Path $repo $r))) { Write-Host "  缺失引用: $r"; $allRefs = $false }
}
$results += [pscustomobject]@{ No = 4; Name = "boot.json 引用路径全部存在"; Ok = $allRefs }

$results | Format-Table -AutoSize
$allOk = (($results | Where-Object { -not $_.Ok }).Count) -eq 0
$sha = (Get-FileHash -LiteralPath $out -Algorithm SHA256).Hash
Write-Host "VERIFIER: $(if ($allOk) { '4/4 PASS' } else { 'FAIL' })"
Write-Host "产物: $out"
Write-Host "SHA256: $sha"
if (-not $allOk) { exit 1 }

if ($BuildZip) {
    $tmp = Join-Path $env:TEMP ("mbce_cot_zip_" + [guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Path $tmp | Out-Null
    try {
        Copy-Item -LiteralPath (Join-Path $repo "boot.json") -Destination $tmp
        Copy-Item -LiteralPath (Join-Path $repo "README.md") -Destination $tmp
        New-Item -ItemType Directory -Path (Join-Path $tmp "javascript") | Out-Null
        Copy-Item -LiteralPath $out -Destination (Join-Path $tmp "javascript")
        Copy-Item -LiteralPath (Join-Path $repo "twee") -Destination $tmp -Recurse
        $zip = Join-Path $repo "MapleBirchCE-CoT-$($boot.version).mod.zip"
        if (Test-Path -LiteralPath $zip) { Remove-Item -LiteralPath $zip -Force }
        Compress-Archive -Path (Join-Path $tmp "boot.json"), (Join-Path $tmp "README.md"), (Join-Path $tmp "javascript"), (Join-Path $tmp "twee") -DestinationPath $zip
        Write-Host "ZIP: $zip"
        Write-Host "ZIP SHA256: $((Get-FileHash -LiteralPath $zip -Algorithm SHA256).Hash)"
    } finally {
        Remove-Item -Recurse -Force -LiteralPath $tmp -ErrorAction SilentlyContinue
    }
}
